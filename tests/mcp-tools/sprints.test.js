function setupMockRef(abbreviation = 'TST', extraHandlers = {}) {
  const pushKey = '-newSprintKey';
  mockPush.mockReturnValue({
    key: pushKey,
    set: mockSet
  });

  mockRef.mockImplementation((path) => {
    if (path.includes('/abbreviation')) {
      return {
        once: vi.fn().mockResolvedValue({ val: () => abbreviation })
      };
    }
    // Allow custom handlers by path pattern (check longest patterns first)
    const sortedPatterns = Object.keys(extraHandlers).sort((a, b) => b.length - a.length);
    for (const pattern of sortedPatterns) {
      if (path.includes(pattern)) {
        return extraHandlers[pattern](path);
      }
    }
    return {
      once: mockOnce,
      set: mockSet,
      update: mockUpdate,
      push: () => mockPush()
    };
  });

  // Mock Firestore transaction for counter
  mockTransaction.mockImplementation(async (fn) => {
    const mockDocSnap = { exists: true, data: () => ({ lastId: 5 }) };
    const mockTransactionObj = {
      get: vi.fn().mockResolvedValue(mockDocSnap),
      set: vi.fn()
    };
    return fn(mockTransactionObj);
  });
}

// ──────────────────────────────────────────────
// Sprint = 1 day strict policy (PMC-TSK-0072)
// ──────────────────────────────────────────────
describe('MCP Sprint tools - Sprint = 1 day strict policy', () => {
  const NOW = new Date('2026-06-07T15:30:00.000Z');
  const BOUNDS = {
    startDate: '2026-06-07T00:00:00.000Z',
    endDate: '2026-06-07T23:59:59.999Z'
  };

  beforeEach(() => {
    vi.clearAllMocks();
    mockUserId = 'geniova-mcp';
  });

  it('auto-generates the title as "Sprint N - YYYYMMDD" when none is provided', async () => {
    setupMockRef();
    mockOnce.mockResolvedValue({ val: () => null }); // no existing sprints

    const result = await createSprint(
      { projectId: 'TestProject' },
      { now: NOW }
    );

    const data = JSON.parse(result.content[0].text);
    expect(data.message).toBe('Sprint created successfully');
    expect(data.title).toBe('Sprint 1 - 20260607');
    expect(data.startDate).toBe(BOUNDS.startDate);
    expect(data.endDate).toBe(BOUNDS.endDate);
    expect(data.durationDays).toBe(1);
    expect(data.autoGenerated).toBe(true);
  });

  it('uses next-of-year correlative based on existing sprints', async () => {
    setupMockRef();
    mockOnce.mockResolvedValue({
      val: () => ({
        '-a': { startDate: '2026-01-02T00:00:00.000Z', title: 'Sprint 1 - 20260102' },
        '-b': { startDate: '2026-03-15T00:00:00.000Z', title: 'Sprint 17 - 20260315' },
        '-legacy': { startDate: '2026-02-01', title: 'Sprint Global 2026' } // unparseable
      })
    });

    const result = await createSprint(
      { projectId: 'TestProject' },
      { now: NOW }
    );

    const data = JSON.parse(result.content[0].text);
    expect(data.title).toBe('Sprint 18 - 20260607');
  });

  it('appends optional suffix when auto-generating', async () => {
    setupMockRef();
    mockOnce.mockResolvedValue({ val: () => null });

    const result = await createSprint(
      { projectId: 'TestProject', suffix: 'Foundations' },
      { now: NOW }
    );

    const data = JSON.parse(result.content[0].text);
    expect(data.title).toBe('Sprint 1 - 20260607 - Foundations');
  });

  it('accepts an explicit title that conforms to the format', async () => {
    setupMockRef();
    mockOnce.mockResolvedValue({ val: () => null });

    const result = await createSprint(
      { projectId: 'TestProject', title: 'Sprint 42 - 20260607 - Hotfix' },
      { now: NOW }
    );

    const data = JSON.parse(result.content[0].text);
    expect(data.title).toBe('Sprint 42 - 20260607 - Hotfix');
    expect(data.autoGenerated).toBe(false);
  });

  it('rejects an explicit title that does not conform', async () => {
    setupMockRef();
    mockOnce.mockResolvedValue({ val: () => null });

    await expect(createSprint(
      { projectId: 'TestProject', title: 'Sprint 1 - June 2026' },
      { now: NOW }
    )).rejects.toThrow(/invalid sprint title/i);
  });

  it('respects explicit startDate and endDate when both are provided', async () => {
    setupMockRef();
    mockOnce.mockResolvedValue({ val: () => null });

    const result = await createSprint(
      {
        projectId: 'TestProject',
        startDate: '2026-07-10',
        endDate: '2026-07-14'
      },
      { now: NOW }
    );

    const data = JSON.parse(result.content[0].text);
    expect(data.startDate).toBe('2026-07-10T00:00:00.000Z');
    expect(data.endDate).toBe('2026-07-14T23:59:59.999Z');
    expect(data.durationDays).toBe(5);
    expect(data.title).toBe('Sprint 1 - 20260710');
    expect(data.autoGenerated).toBe(true);
    expect(data.warnings).toBeUndefined();
  });

  it('treats a single startDate without endDate as a 1-day sprint on that day', async () => {
    setupMockRef();
    mockOnce.mockResolvedValue({ val: () => null });

    const result = await createSprint(
      { projectId: 'TestProject', startDate: '2026-07-10' },
      { now: NOW }
    );

    const data = JSON.parse(result.content[0].text);
    expect(data.startDate).toBe('2026-07-10T00:00:00.000Z');
    expect(data.endDate).toBe('2026-07-10T23:59:59.999Z');
    expect(data.durationDays).toBe(1);
    expect(data.title).toBe('Sprint 1 - 20260710');
  });

  it('uses today as start when only endDate is provided', async () => {
    setupMockRef();
    mockOnce.mockResolvedValue({ val: () => null });

    const result = await createSprint(
      { projectId: 'TestProject', endDate: '2026-06-09' },
      { now: NOW }
    );

    const data = JSON.parse(result.content[0].text);
    expect(data.startDate).toBe(BOUNDS.startDate);
    expect(data.endDate).toBe('2026-06-09T23:59:59.999Z');
    expect(data.durationDays).toBe(3);
  });

  it('rejects endDate before startDate', async () => {
    setupMockRef();
    mockOnce.mockResolvedValue({ val: () => null });

    await expect(createSprint(
      {
        projectId: 'TestProject',
        startDate: '2026-07-10',
        endDate: '2026-07-05'
      },
      { now: NOW }
    )).rejects.toThrow(/endDate.*on or after.*startDate/i);
  });

  it('rejects unparseable startDate', async () => {
    setupMockRef();
    mockOnce.mockResolvedValue({ val: () => null });

    await expect(createSprint(
      { projectId: 'TestProject', startDate: 'not-a-date' },
      { now: NOW }
    )).rejects.toThrow(/Invalid startDate/i);
  });

  it('includes the sprint policy note in the response', async () => {
    setupMockRef();
    mockOnce.mockResolvedValue({ val: () => null });

    const result = await createSprint(
      { projectId: 'TestProject' },
      { now: NOW }
    );

    const data = JSON.parse(result.content[0].text);
    expect(data.policy).toMatch(/Sprint = 1 day of work by default/i);
    expect(data.policy).toMatch(/not Scrum/i);
  });

  it('is idempotent: returns the existing sprint of today instead of creating a duplicate', async () => {
    setupMockRef();
    mockOnce.mockResolvedValue({
      val: () => ({
        '-todays': {
          cardId: 'TST-SPR-0099',
          title: 'Sprint 7 - 20260607',
          startDate: BOUNDS.startDate,
          endDate: BOUNDS.endDate
        }
      })
    });

    const result = await createSprint(
      { projectId: 'TestProject' },
      { now: NOW }
    );

    const data = JSON.parse(result.content[0].text);
    expect(data.idempotent).toBe(true);
    expect(data.cardId).toBe('TST-SPR-0099');
    expect(data.title).toBe('Sprint 7 - 20260607');
    expect(mockSet).not.toHaveBeenCalled(); // no new sprint persisted
  });

  it('warns when suffix is passed together with an explicit title', async () => {
    setupMockRef();
    mockOnce.mockResolvedValue({ val: () => null });

    const result = await createSprint(
      { projectId: 'TestProject', title: 'Sprint 1 - 20260607', suffix: 'Ignored' },
      { now: NOW }
    );

    const data = JSON.parse(result.content[0].text);
    expect(data.title).toBe('Sprint 1 - 20260607');
    expect(data.warnings).toEqual(expect.arrayContaining([
      expect.stringMatching(/Ignored "suffix"/i)
    ]));
  });
});

