describe('MCP Sprint tools - AC3: Sprint date range on In Progress', () => {
  beforeEach(() => {
    vi.clearAllMocks();
    mockUserId = 'geniova-mcp';
  });

  it('should reject moving task to In Progress when today is outside sprint date range', async () => {
    const taskFirebaseId = '-task1';
    const sprintCardId = 'TST-SPR-0001';

    const taskOnce = vi.fn().mockResolvedValue({
      exists: () => true,
      val: () => ({
        cardId: 'TST-TSK-0001',
        title: 'Test task',
        status: 'To Do',
        sprint: sprintCardId,
        developer: 'dev_001',
        validator: 'stk_001',
        devPoints: 2,
        businessPoints: 3,
        acceptanceCriteria: 'Some criteria',
        epic: 'TST-EPC-0001'
      })
    });
    const sprintOnce = vi.fn().mockResolvedValue({
      val: () => ({
        '-sprint1': {
          cardId: sprintCardId,
          title: 'Sprint 1',
          startDate: '2025-01-01',
          endDate: '2025-01-15'
        }
      })
    });

    setupMockRef('TST', {
      [`TASKS_TestProject/${taskFirebaseId}`]: () => ({
        once: taskOnce,
        update: mockUpdate
      }),
      ['SPRINTS_TestProject']: () => ({
        once: sprintOnce
      }),
      ['/scoringSystem']: () => ({
        once: vi.fn().mockResolvedValue({ val: () => '1-5' })
      })
    });

    await expect(updateCard({
      projectId: 'TestProject',
      type: 'task',
      firebaseId: taskFirebaseId,
      updates: {
        status: 'In Progress',
        developer: 'dev_001',
        validator: 'stk_001',
        sprint: sprintCardId,
        devPoints: 2,
        businessPoints: 3,
        acceptanceCriteria: 'Some criteria',
        epic: 'TST-EPC-0001'
      }
    })).rejects.toThrow(/sprint.*date|date.*sprint/i);
  });

  it('should allow moving task to In Progress when sprint has no dates (skip validation)', async () => {
    const taskFirebaseId = '-task1';
    const sprintCardId = 'TST-SPR-0001';
    const sprintFirebaseId = '-sprint1';

    const taskData = {
      cardId: 'TST-TSK-0001',
      title: 'Test task',
      status: 'To Do',
      sprint: sprintCardId,
      developer: 'dev_001',
      validator: 'stk_001',
      devPoints: 2,
      businessPoints: 3,
      acceptanceCriteria: 'Some criteria',
      epic: 'TST-EPC-0001'
    };

    const taskOnce = vi.fn()
      .mockResolvedValueOnce({
        exists: () => true,
        val: () => ({ ...taskData })
      })
      .mockResolvedValueOnce({
        val: () => ({ ...taskData, status: 'In Progress' })
      });
    const sprintOnce = vi.fn().mockResolvedValue({
      val: () => ({
        [sprintFirebaseId]: {
          cardId: sprintCardId,
          title: 'Sprint 1'
          // No startDate/endDate
        }
      })
    });
    const sprintItemUpdate = vi.fn().mockResolvedValue();

    setupMockRef('TST', {
      [`TASKS_TestProject/${taskFirebaseId}`]: () => ({
        once: taskOnce,
        update: mockUpdate
      }),
      ['SPRINTS_TestProject']: (path) => {
        if (path.includes(sprintFirebaseId)) {
          return { update: sprintItemUpdate };
        }
        return { once: sprintOnce, update: sprintItemUpdate };
      },
      ['/scoringSystem']: () => ({
        once: vi.fn().mockResolvedValue({ val: () => '1-5' })
      })
    });

    const result = await updateCard({
      projectId: 'TestProject',
      type: 'task',
      firebaseId: taskFirebaseId,
      updates: {
        status: 'In Progress',
        developer: 'dev_001',
        validator: 'stk_001',
        sprint: sprintCardId,
        devPoints: 2,
        businessPoints: 3,
        acceptanceCriteria: 'Some criteria',
        epic: 'TST-EPC-0001'
      }
    });

    const data = JSON.parse(result.content[0].text);
    expect(data.message).toBe('Card updated successfully');
  });
});

